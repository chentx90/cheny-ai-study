# Node 1: convert - 小说 → 按视频时长切分的分镜片段
# ══════════════════════════════════════════════════════════
# 职责: 按"画面表达需要的视频时长"(4-15秒/段)把原文切成小片段，
#       每段保留对应原文 + 时长 + 场景信息(景别|天气|时间|地点)。
#       不写画面文案、不分对话；人物/物品留空，由后续 extract/bind 填。

CONVERT_SYSTEM = "你是专业影视分镜师，擅长按视频时长把小说原文切分为一个个可拍摄的画面片段。"

CONVERT_USER = """请将本集小说原文，按"每个画面表达需要的视频时长"切分为分镜片段序列。

## 全篇大纲（背景参考）
{outline}

## 上集结尾（衔接参考）
{prev_summary}

## 下集开头（预留空间）
{next_summary}

## 本集原文
{text}

## 切分规则
1. 以"一个画面镜头需要的视频时长"为单位切分，每段控制在 4-15 秒画面量
   - 一句对话、一个简单动作 ≈ 4-6 秒
   - 一段连续动作、一次场景描写 ≈ 8-12 秒
   - 信息密集或情绪铺陈 ≈ 12-15 秒
2. 严格按原文顺序切分，不遗漏、不改写、不虚构
3. source_text 必须是原文的连续片段，所有片段拼接 = 完整原文

## 每段输出字段
- duration: 该片段预估视频时长（4~15 的整数，单位秒）
- source_text: 本片段对应的原文（原样保留，后续据此生成画面）
- scene_info: 场景信息，格式「景别|天气|时间|地点」
  - 景别: 远景/全景/中景/近景/特写 之一
  - 天气/时间/地点: 据原文判断，无法判断填「未知」
  - 例: 中景|晴|黄昏|山路
- characters: 留空数组 []（后续实体绑定填充）
- items: 留空数组 []（后续实体绑定填充）

## 输出
严格 JSON 数组，不要多余文字：
[{{"duration":8,"source_text":"本段原文...","scene_info":"中景|晴|黄昏|山路","characters":[],"items":[]}}]"""


