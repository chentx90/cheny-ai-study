EXTRACT_SYSTEM = "你是影视分镜资产提取助手。"

EXTRACT_USER = """从以下分镜文本中提取所有人物、场景、道具，并判断每个实体的重要程度。

分镜文本:
{panels_text}

已有实体(避免重复):
{existing}

提取规则:
- 同一角色在不同年龄阶段外貌差异明显时，拆分为独立实体，命名加年龄标注
  例: "妹妹(6岁)"、"妹妹(20岁)"，而不是合并为一个"妹妹"
- 场景和道具的 description 中不要出现人名

每个实体需要:
- name: 名字（同角色不同年龄段加括号标注，如"妹妹(6岁)"）
- aliases: 别名（逗号分隔，如"妹妹,小妹"）
- description: 描述
  - 人物: 年龄、性别、发色、服装特征
  - 场景: 环境类型、时间、氛围、主要特征
  - 道具: 外观、材质、颜色、用途
- importance:
  - major = 反复出现、对情节重要、需要保持视觉一致性
  - minor = 只短暂出现一次、背景性存在、文字描述足够

请输出严格JSON:
{{
  "characters": [{{"name":"","aliases":"","description":"","importance":"major"}}],
  "locations":  [{{"name":"","aliases":"","description":"","importance":"minor"}}],
  "items":      [{{"name":"","aliases":"","description":"","importance":"minor"}}]
}}"""


